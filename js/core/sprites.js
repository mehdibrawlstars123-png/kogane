/** Склеивает горизонтальные серии одинаковых пикселей в один <rect> */
function rowRects(row, y, char, fill) {
  const rects = [];
  let start = -1;

  for (let x = 0; x <= row.length; x += 1) {
    const hit = row[x] === char;
    if (hit && start === -1) start = x;
    if (!hit && start !== -1) {
      rects.push(`<rect x="${start}" y="${y}" width="${x - start}" height="1" fill="${fill}"/>`);
      start = -1;
    }
  }
  return rects.join('');
}

/**
 * Возвращает SVG-разметку спрайта.
 * @param {string} name  ключ из MAPS
 * @param {object} opts  { scale, className, light }
 */
export function sprite(name, { scale = 3, className = '', light = 'var(--phos-hi)' } = {}) {
  const map = MAPS[name];
  if (!map) {
    console.warn(`[sprites] нет карты "${name}"`);
    return '';
  }

  const w = Math.max(...map.map((r) => r.length));
  const h = map.length;

  let body = '';
  map.forEach((row, y) => {
    body += rowRects(row, y, '#', 'currentColor');
    body += rowRects(row, y, 'o', light);
  });

  return `<svg class="sprite ${className}" viewBox="0 0 ${w} ${h}" width="${w * scale}" height="${h * scale}" aria-hidden="true">${body}</svg>`;
}

/**
 * Иконка участника — одна цельная фигура.
 *
 * Раньше рисовались два спрайта подряд: «лицо» и отдельный человечек,
 * у которого была своя голова. Получался кружок над фигурой, непонятный
 * ни как голова, ни как шея. Теперь фигура одна: живая или выбывшая.
 */
export function participantIcon(alive = true, scale = 3) {
  return `<span class="face ${alive ? '' : 'face--dead'}">${
    sprite(alive ? 'figure' : 'figureDead', { scale, className: 'sprite--figure' })
  }</span>`;
}

