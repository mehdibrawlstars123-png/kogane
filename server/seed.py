def seed(session) -> None:
    """Наполняет пустую базу. Повторный вызов безопасен."""
    created = False

    if not session.scalar(select(BaseRule).limit(1)):
        for i, (no, title, jp, text) in enumerate(BASE_RULES):
            session.add(BaseRule(id=no, title=title, jp=jp, text=text, sort=i))
        created = True

    if not session.scalar(select(ShopRule).limit(1)):
        for i, (rid, code, title, jp, cat, text) in enumerate(SHOP_RULES):
            session.add(ShopRule(
                id=rid, code=code, title=title, jp=jp, cat=cat, text=text,
                cost=100, enabled=True, sort=i,
            ))
        created = True

    # Учётные записи распорядителей. Добавляются по одной: если почта уже
    # заведена, запись не трогается — пароль и код, изменённые в панели,
    # переживают перезапуск сервера.
    for acc in ADMIN_ACCOUNTS:
        if session.scalar(select(User).where(User.email == acc["email"])):
            continue
        session.add(User(
            id=acc["id"],
            email=acc["email"],
            pass_hash=hash_secret(acc["password"]),
            code_hash=hash_secret(acc["code"]) if acc.get("code") else None,
            role="admin",
            state="approved",
            created_at=now_ms(),
            character={
                "name": acc["name"], "nameJp": acc.get("nameJp", "主催者"), "level": "gs",
                "points": 0, "rules": 0, "colony": "tokyo1", "status": "out",
            },
            owned_rules=[],
        ))
        created = True

    if not session.get(Setting, "migration"):
        session.add(Setting(key="migration", value={
            "number": 1, "active": True, "startedAt": now_ms(), "endedAt": None,
            "note": "Первая миграция. Барьеры развёрнуты над десятью колониями.",
        }))
        created = True

    # Музыка событий. Ссылки открываются во встроенном проигрывателе YouTube —
    # чужие записи в проект не копируются, воспроизводит их сам YouTube.
    # kind: youtube (ссылка) | file (свой звуковой файл) | synth (тема системы)
    if not session.get(Setting, "event_music"):
        session.add(Setting(key="event_music", value={
            "sukuna": {"kind": "youtube", "url": "https://youtu.be/EWs7V6RHMe4"},
            "duel":   {"kind": "youtube", "url": "https://youtu.be/44pt8w67S8I"},
            "parade": {"kind": "synth",   "url": ""},
        }))
        created = True

    if not session.get(Setting, "security"):
        session.add(Setting(key="security", value={
            "codeHash": hash_secret(DEFAULT_ADMIN_CODE),
            "codeChanged": False,
            "updatedAt": now_ms(),
        }))
        created = True

    if not session.scalar(select(RuleHistory).limit(1)):
        session.add(RuleHistory(
            id=new_id("rh"), ts=now_ms(), type="base",
            title="Свод базовых правил утверждён", jp="基本規則制定",
            by="Распорядитель игры", colony=None,
        ))
        created = True

    if created:
        session.commit()
